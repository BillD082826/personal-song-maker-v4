import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import NodeID3 from 'node-id3';
import { embedMp3Cover } from '../lib/mp3-cover.mjs';
const audio = await readFile(new URL('./fixtures/cover-test-tone.mp3', import.meta.url));
const jpeg = await readFile(new URL('./fixtures/cover-test-image.jpg', import.meta.url));
const source = NodeID3.update({ album: 'Keep existing album' }, audio);
const original = Buffer.from(source);
const output = await embedMp3Cover(source, jpeg, 'A song — Anniversary');
const tags = NodeID3.read(output);
assert.equal(tags.title, 'A song — Anniversary');
assert.equal(tags.artist, 'LyriBop');
assert.equal(tags.album, 'Keep existing album');
assert.equal(tags.image.type.id, 3);
assert(tags.image.imageBuffer.equals(jpeg));
assert(NodeID3.removeTagsFromBuffer(output).equals(NodeID3.removeTagsFromBuffer(source)));
assert(original.equals(source));
const second = await embedMp3Cover(output, jpeg, 'Updated title');
assert.equal(NodeID3.read(second).title, 'Updated title');
assert(NodeID3.removeTagsFromBuffer(second).equals(NodeID3.removeTagsFromBuffer(source)));
await assert.rejects(embedMp3Cover(Buffer.from('invalid'), jpeg, 'Bad'));
console.log('PASS: embedded cover/title/artist, other metadata preserved, repeat tagging, unchanged audio payload/source, invalid audio rejection. Synthetic fixtures only.');
